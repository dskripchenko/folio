export type IconName = keyof typeof PATHS

export function icon(name: IconName, size = 16): SVGSVGElement {
  const t = document.createElement('template')
  t.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false" class="icon-svg">${PATHS[name]}</svg>`
  return t.content.firstElementChild as SVGSVGElement
}

/** A button that is an icon: its name is its label for assistive technology and its tooltip. */
export function iconButton(name: IconName, label: string, click: (event: MouseEvent) => void, testid?: string): HTMLButtonElement {
  const b = document.createElement('button')
  b.type = 'button'
  b.className = 'icon-button'
  b.title = label
  b.setAttribute('aria-label', label)
  if (testid) b.dataset.testid = testid
  b.append(icon(name))
  b.addEventListener('click', click)
  return b
}
